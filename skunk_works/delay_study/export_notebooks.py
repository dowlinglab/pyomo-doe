"""Promote complete workshop notebook cells into deterministic Python scripts.

This mechanical migration preserves cell order, comments and scientific code.
Colab shell escapes become explicit subprocess calls. The exported scripts run
from the original notebook directory so relative inputs keep their old meaning.
The later delay-study modules are the source of truth for new research methods.
"""
from __future__ import annotations

import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = Path(__file__).resolve().with_name("notebook_scripts")
NAMES = [
    "tclab_model", "numpy_simulation", "pyomo_simulation",
    "experiment_abstraction", "parmest", "parmest_uncertainty_quantification",
    "parmest_multistart", "parmest_profilelikelihood", "parmest_regularization",
    "doe_optimize", "doe_optimize_objectives", "doe_optimize_symbolic",
    "doe_multiexperiment",
]


def portable_cell(source: str) -> str:
    """Translate only notebook shell lines; reject unhandled notebook syntax."""
    result = []
    for line in source.splitlines():
        stripped = line.lstrip()
        indentation = line[:len(line) - len(stripped)]
        if stripped.startswith("!"):
            command = stripped[1:]
            if "{" in command or "$" in command:
                raise ValueError("Interpolated notebook shell escape needs review")
            line = indentation + "subprocess.run(shlex.split(" + repr(command) + "), check=True)"
        elif stripped.startswith("%"):
            raise ValueError("Notebook magic needs explicit review: " + stripped)
        result.append(line)
    return "\n".join(result) + "\n"


def export(name: str) -> dict:
    path = ROOT / "notebooks" / (name + ".ipynb")
    notebook = json.loads(path.read_text())
    body = []
    cell_hashes = []
    code = []
    for index, cell in enumerate(notebook["cells"]):
        source = "".join(cell.get("source", []))
        if cell["cell_type"] == "code":
            transformed = portable_cell(source)
            ast.parse(transformed)
            body.extend([f"# %% [code cell {index}]", transformed])
            code.append(transformed)
            cell_hashes.append({"cell": index, "source_sha256": hashlib.sha256(source.encode()).hexdigest()})
        elif cell["cell_type"] == "markdown":
            body.append(f"# %% [markdown cell {index}]")
            body.extend(("# " + line).rstrip() for line in source.splitlines())
    cell_source = "\n".join(body)
    scientific_ast = ast.dump(ast.parse("\n".join(code)), include_attributes=False)
    header = f'''"""Python migration of notebooks/{name}.ipynb; generated by export_notebooks.py.

This is an executable driver, not an importable library.
Run with the workshop Pyomo environment. Custom ParmEst/DoE features require
the workshop Pyomo branch described in the repository README.
"""
from pathlib import Path
import os
import shlex
import subprocess
import sys
notebook_dir = Path(__file__).resolve().parents[3] / "notebooks"
sys.path.insert(0, str(notebook_dir))
os.chdir(notebook_dir)
'''
    script = header + "\n" + cell_source.rstrip() + "\n"
    tree = ast.parse(script)
    migrated = tree.body[len(ast.parse(header).body):]
    if ast.dump(ast.Module(body=migrated, type_ignores=[]), include_attributes=False) != scientific_ast:
        raise RuntimeError("Migration altered scientific cell AST: " + name)
    target = DEST / (name + ".py")
    target.write_text(script)
    return {"notebook": str(path.relative_to(ROOT)), "notebook_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "script": str(target.relative_to(ROOT)), "script_sha256": hashlib.sha256(script.encode()).hexdigest(),
            "code_cells": cell_hashes, "scientific_ast_preserved": True}


def main() -> None:
    DEST.mkdir(exist_ok=True)
    rows = [export(name) for name in NAMES]
    (DEST / "manifest.json").write_text(json.dumps({"migration": "ordered cells; shell escape translation only", "scripts": rows}, indent=2) + "\n")
    print(f"Exported {len(rows)} scripts; scientific ASTs preserved.")


if __name__ == "__main__":
    main()
