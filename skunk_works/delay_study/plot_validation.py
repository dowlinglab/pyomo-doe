"""Held-out file diagnostics and working-OU residual correlations; no refitting."""
import os
os.environ.setdefault("MPLBACKEND", "Agg")
os.environ.setdefault("MPLCONFIGDIR", "/private/tmp/tclab-matplotlib")

import argparse
import hashlib
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

import figure_style as fs
from run_fits import save_json

HERE = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, default=HERE/"results")
    parser.add_argument("--output", type=Path, default=HERE/"manuscript/figures")
    parser.add_argument("--tables", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    args.tables.mkdir(parents=True, exist_ok=True)
    inputs, data, outputs = {}, {}, []

    def read(path):
        inputs[str(path)] = sha(path)
        return json.loads(path.read_text())

    def save(figure, name, notes):
        fs.grayscale_preview(figure, str(args.output/name))
        fs.save_fig(figure, str(args.output/name), sources=list(inputs), notes=notes)
        outputs.append(name)
        plt.close(figure)

    manifest = read(args.results/"manifest.json")
    if manifest["status"] != "complete":
        raise RuntimeError("Baseline fit sweep is not complete")
    files = sorted(manifest["validation_files"])
    if len(files) != 11 or len(set(files)) != 11:
        raise RuntimeError("Expected eleven duplicate-excluded validation files")
    labels = ["V"+str(i+1).zfill(2) for i in range(len(files))]
    models = [(1, r"$n=1$", 5, "-"), (2, r"$n=2$", 1, "--"),
              (12, r"$n=12$", 3, "-."), (0, "Pure delay", 4, ":")]
    figure, axes = fs.figure(fs.MULTI_PANEL, nrows=2, sharex=True)
    validation, metadata, summary_rows = {}, [], []
    for order, title, color, style in models:
        model = "chain_n"+str(order) if order else "pure_delay_n0"
        key = "joint__"+model+"_io_cold_linear_exact"
        fit = read(args.results/"fits"/(key+".json"))
        records = {row["dataset"]: row for row in fit["validation"]}
        if set(records) != set(files):
            raise RuntimeError("Validation file selection differs between models")
        rows = [records[name] for name in files]
        for ax, metric in zip(axes, ("rmse_C", "bias_C")):
            ax.plot(np.arange(11), [row[metric] for row in rows], color=fs.color(color), linestyle=style,
                    marker="o", markersize=4, linewidth=fs.DENSE_LINEWIDTH, label=title)
        total_sse = sum(row["n"]*row["rmse_C"]**2 for row in rows)
        bias_sse = sum(row["n"]*row["bias_C"]**2 for row in rows)
        validation[key] = {"files": rows, "calibration_rmse_C": fit["fit"]["rmse"],
                           "pooled_rmse_C": float(np.sqrt(total_sse/sum(row["n"] for row in rows))),
                           "per_file_bias_fraction_of_pooled_SSE": float(bias_sse/total_sse),
                           "notice": "Bias decomposition is retrospective; file-specific mean subtraction is not a prospective correction or an estimated physical mechanism."}
        summary_rows.append(title+" & "+f"{fit['fit']['rmse']:.4f} & {validation[key]['pooled_rmse_C']:.4f} & {100*bias_sse/total_sse:.1f}"+r" \\")
        if order == 1:
            prediction_path = args.results/fit["prediction_file"]
            if sha(prediction_path) != fit["prediction_sha256"]:
                raise RuntimeError("Validation prediction input changed")
            inputs[str(prediction_path)] = sha(prediction_path)
            predictions = pd.read_csv(prediction_path)
            for code, name in zip(labels, files):
                group = predictions[(predictions.role == "validation") & (predictions.experiment == name)]
                metadata.append({"code": code, "file": name, "residual_count": len(group)-1,
                                 "duration_s": float(group.time_s.iloc[-1]-group.time_s.iloc[0]),
                                 "conditioned_initial_C": float(group.measured_C.iloc[0])})
    axes[0].set(title="(a) Error on each held-out file", ylabel=r"RMSE ($^\circ$C)")
    axes[1].set(title="(b) Signed mean error", ylabel=r"Bias ($^\circ$C)", xlabel="Validation file")
    axes[1].axhline(0., color="0.65", linewidth=fs.REFERENCE_LINEWIDTH)
    axes[1].set_xticks(range(11))
    axes[1].set_xticklabels(labels)
    figure.legend(*axes[0].get_legend_handles_labels(), loc="upper center", ncol=4, bbox_to_anchor=(.5, 1.015), columnspacing=1.)
    figure.tight_layout(rect=(0., 0., 1., .93), h_pad=1.8)
    data["validation_errors"] = validation
    data["validation_file_map"] = metadata
    table_path = args.tables/"validation_file_map.tex"
    table = ["% Generated by plot_validation.py; see validation_figure_manifest.json.",
             r"\begin{table}[tbp]", r"\centering\small", r"\begin{tabular}{llrrr}", r"\toprule",
             r"Code & Supplied filename suffix & Duration (s) & $T_0$ (${}^\circ$C) & $N$ \\", r"\midrule"]
    for item in metadata:
        suffix = item["file"].removeprefix("validation_experiment_")
        table.append(item["code"]+r" & \path{"+suffix+"} & "+f"{item['duration_s']:.1f} & {item['conditioned_initial_C']:.2f} & {item['residual_count']}"+r" \\")
    table.extend([r"\bottomrule", r"\end{tabular}",
                  r"\caption{Validation-file codes. Restore the common prefix \texttt{validation\_experiment\_} to each supplied filename. $N$ excludes the initial temperature, which also supplies the assumed ambient for that file; it is not an independent ambient measurement. File labels do not establish independent replication or a change in physical environment.}",
                  r"\label{tab:validation-files}", r"\end{table}", ""])
    table_path.write_text("\n".join(table))
    summary_path = args.tables/"validation_summary.tex"
    table = ["% Generated by plot_validation.py; see validation_figure_manifest.json.", r"\begin{table}[tbp]", r"\centering\small",
             r"\begin{tabular}{lrrr}", r"\toprule", r"Model & Calibration RMSE & Held-out RMSE & File-mean share (\%) \\", r"\midrule",
             *summary_rows, r"\bottomrule", r"\end{tabular}",
             r"\caption{Joint cold baseline fits evaluated without refitting on eleven duplicate-excluded validation files. RMSE values are in degrees Celsius; the held-out value pools all retained observations rather than averaging file RMSEs. File-mean share is $100\sum_j N_j\bar e_j^2/\sum_j\sum_i e_{ij}^2$, the retrospective algebraic contribution of each file's mean residual to pooled held-out error. It is not a causal attribution or a prospective bias correction.}",
             r"\label{tab:validation-summary}", r"\end{table}", ""]
    summary_path.write_text("\n".join(table))
    save(figure, "validation_errors", "Four joint cold baseline fits, eleven supplied validation files after excluding numeric duplicates of calibration data. Errors exclude each conditioned initial observation. Bias is prediction minus observation. Lines connect categorical file codes as visual guides, not a time series or independent replication claim. Model parameters are not refitted on these files; per-file ambient and initial temperature follow the original first-reading assumption. No error bar or prediction interval is implied.")

    diagnostics_path = args.results/"ou/residual_diagnostics.json"
    diagnostics = read(diagnostics_path)
    figure, axes = fs.figure(fs.MULTI_PANEL, nrows=2, ncols=2, sharex=True, sharey=True)
    correlations = {}
    for order, title, color, style in models:
        model = "chain_n"+str(order) if order else "pure_delay_n0"
        key = "joint__"+model+"_io_cold_linear_exact"
        correlations[key] = {}
        for column, experiment in enumerate(["sine", "step"]):
            correlations[key][experiment] = {}
            for row, metric in enumerate(["raw_C", "innovation_C"]):
                acf = diagnostics[key][experiment][metric]["acf_lags_1_to_30"]
                correlations[key][experiment][metric] = acf
                axes[row, column].plot(range(1, len(acf)+1), acf, color=fs.color(color), linestyle=style,
                                       marker="o", markersize=fs.DENSE_MARKERSIZE, linewidth=fs.DENSE_LINEWIDTH, label=title)
    for i, ax in enumerate(axes.flat):
        ax.axhline(0., color="0.65", linewidth=fs.REFERENCE_LINEWIDTH)
        ax.set(xlim=(0., 31.), ylim=(-.65, 1.05), title=["(a) Sine, raw", "(b) Step, raw", "(c) Sine, filtered", "(d) Step, filtered"][i])
    axes[0, 0].set_ylabel("Residual ACF")
    axes[1, 0].set_ylabel("Innovation ACF")
    for ax in axes[-1]:
        ax.set_xlabel("Lag (retained samples)")
    figure.legend(*axes[0, 0].get_legend_handles_labels(), loc="upper center", ncol=4, bbox_to_anchor=(.5, 1.015), columnspacing=1.)
    figure.tight_layout(rect=(0., 0., 1., .93), h_pad=1.8, w_pad=1.)
    data["ou_correlations"] = correlations
    save(figure, "ou_correlations", "Centered sample autocorrelations of raw residuals and filtered innovations from each model's own joint cold OU mean/covariance fit. Columns are calibration records, rows before/after the working stationary OU filter. Strong negative first-lag innovation correlation challenges the combined mean/covariance model; it does not alone identify a physical disturbance or sensor-noise mechanism. No nominal whiteness-test confidence band is shown.")
    path = args.output/"validation_plot_data.json"
    save_json(path, data)
    result = {"producer_sha256": {name: sha(HERE/name) for name in ("plot_validation.py", "figure_style.py")},
              "input_sha256": inputs, "plot_data_sha256": sha(path), "figures": outputs,
              "generated_table": {"path": str(table_path), "sha256": sha(table_path)},
              "generated_summary_table": {"path": str(summary_path), "sha256": sha(summary_path)},
              "status": "generated_awaiting_independent_numeric_and_visual_audit"}
    snapshot = HERE.parents[1]/"snapshot.json"
    if snapshot.exists():
        result["source_commit"] = json.loads(snapshot.read_text())["commit"]
        (args.output/"validation_source_snapshot.json").write_text(snapshot.read_text())
        (args.tables/"validation_source_snapshot.json").write_text(snapshot.read_text())
    save_json(args.output/"validation_figure_manifest.json", result)


if __name__ == "__main__":
    main()
