"""Format declared coverage rows and direct scalar fields; no new statistics."""
import argparse
import json
from pathlib import Path

from plot_coverage import MODELS, NOISES, load_delay_summary, sha
from run_fits import save_json

HERE = Path(__file__).resolve().parent
TABLE_METHODS = ["iid_known_sigma", "iid_estimated_sigma", "hac60", "profile_estimated_sigma_iid"]


def integer(value):
    if value is None or float(value) != int(value):
        raise RuntimeError("A coverage count is not an integer")
    return str(int(value))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--coverage", type=Path, default=HERE/"results/coverage")
    parser.add_argument("--summary", type=Path, default=HERE/"results/coverage_summary")
    parser.add_argument("--config", type=Path, default=HERE/"coverage_config.json")
    parser.add_argument("--figures", type=Path, default=HERE/"manuscript/figures")
    parser.add_argument("--output", type=Path, default=HERE/"manuscript/tables")
    args = parser.parse_args()
    rows, inputs = load_delay_summary(args.summary, args.coverage, args.config)
    audit_path = args.figures/"coverage_numeric_audit.json"
    audit = json.loads(audit_path.read_text())
    if audit["status"] != "passed" or audit["delay_rows"] != 84 or audit["source_summary_inputs"] != inputs:
        raise RuntimeError("Independent coverage figure-data audit required")
    inputs[str(audit_path)] = sha(audit_path)
    indexed = {(r["case"], r["true_noise"], r["method"]): r for r in rows}
    lines = ["% Generated by render_coverage_table.py; see coverage_table_manifest.json.",
             r"\begin{table}[tbp]", r"\centering\small", r"\begin{tabular}{llrrrr}", r"\toprule",
             r"Model & Error law & IID known & IID fitted & HAC60 & Profile fitted \\", r"\midrule"]
    for case, title, _, _ in MODELS:
        for noise, _ in NOISES:
            cells = []
            for method in TABLE_METHODS:
                row = indexed[(case, noise, method)]
                cells.append(integer(row["covered"])+"/"+integer(row["defined"]) if row["defined"] else "--")
            lines.append(title+" & "+{"iid": "IID", "ou10": "OU10", "ou60": "OU60"}[noise]+" & "+" & ".join(cells)+r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{Delay-interval coverage counts for four selected procedures. Each entry is covered/defined, from \CoverageReplicates{} requested datasets at that generating point and true covariance; -- would denote no defined interval. All intervals have nominal 95\% reference levels. IID known/fitted refer to Gaussian log-Wald intervals; HAC60 uses a Bartlett bandwidth of 60 retained samples; profile fitted uses a common profiled IID variance and retains disconnected components. OU10/OU60 are true correlation lengths in seconds, with fixed marginal standard deviation. Full method-specific failure bounds and grid diagnostics are retained in the coverage CSV; Wilson Monte Carlo intervals and all seven methods appear in Fig.~\ref{fig:coverage-delay}.}",
              r"\label{tab:coverage-delay}", r"\end{table}", ""]
    selected = indexed[(MODELS[1][0], "ou60", "profile_known_sigma_iid")]
    values = {"CoverageReplicates": integer(selected["requested"]),
              "CoverageTotalDatasets": integer(json.loads((args.summary/"audit.json").read_text())["requested_draws"]),
              "CoverageTwoStageOUKnownGridChanges": integer(selected["quadratic_interpolation_coverage_class_changes"])}
    args.output.mkdir(parents=True, exist_ok=True)
    table, macros = args.output/"coverage_rates.tex", args.output/"coverage_values.tex"
    table.write_text("\n".join(lines))
    macros.write_text("% Direct fields formatted from the audited coverage summary.\n"+
                      "\n".join("\\newcommand{\\"+key+"}{"+value+"}" for key, value in values.items())+"\n")
    report = {"status": "generated_awaiting_printed_cell_and_visual_audit", "input_sha256": inputs,
              "producer_sha256": sha(HERE/"render_coverage_table.py"),
              "outputs": {p.name: sha(p) for p in [table, macros]}, "methods": TABLE_METHODS,
              "macro_source": {"case": selected["case"], "true_noise": "ou60", "method": "profile_known_sigma_iid"}}
    snapshot = HERE.parents[1]/"snapshot.json"
    if snapshot.exists():
        report["source_commit"] = json.loads(snapshot.read_text())["commit"]
        (args.output/"coverage_table_source_snapshot.json").write_text(snapshot.read_text())
    save_json(args.output/"coverage_table_manifest.json", report)


if __name__ == "__main__":
    main()
