"""Generate family-boundary and coordinate-correlation tables from saved results."""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from run_fits import save_json

HERE = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_table(path, header, rows, caption, reference):
    lines = ["% Generated by render_structural_tables.py; edit the producer, not this table.",
             r"\begin{table}[tbp]", r"\centering", r"\small", "\\begin{tabular}{l"+"r"*(len(header)-1)+"}",
             r"\toprule", " & ".join(header)+r" \\", r"\midrule"]
    lines.extend(" & ".join(row)+r" \\" for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}", "\\caption{"+caption+"}", "\\label{"+reference+"}", r"\end{table}", ""])
    path.write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, default=HERE/"results")
    parser.add_argument("--output", type=Path, default=HERE/"manuscript/tables")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    inputs, values = {}, {}
    source = args.results/"family_uncertainty/summary.csv"
    inputs[str(source)] = sha(source)
    summary = pd.read_csv(source)
    summary = summary[summary.case == "joint__chain_n1_io_cold_linear_exact"]
    names = ["CpH_inf_J_K", "CpH_sup_J_K", "CpS_sup_J_K", "Ub_sup_W_K"]
    labels = [r"$\inf\CpH$ (J/K)", r"$\sup\CpH$ (J/K)", r"$\sup\CpS$ (J/K)", r"$\sup\Ub$ (W/K)"]
    rows = []
    for name, label in zip(names, labels):
        methods, numeric = [], []
        for method in ["parametric", "block60"]:
            row = summary[(summary.function == name) & (summary.method == method)].iloc[0]
            methods.append("$["+f"{row.lower:.4g},{row.upper:.4g}"+"]$")
            numeric.extend([float(row.lower), float(row.upper)])
        numeric.insert(0, float(row.point))
        values[name] = numeric
        rows.append([label, f"{row.point:.4g}"]+methods)
    write_table(args.output/"family_limits.tex", ["Boundary function", "Fitted value", "IID simulation", "Circular block 60"], rows,
                "Identifiable boundary functions for the full strictly positive original-model family, propagated from the joint cold one-stage transfer fit. Intervals are conditional 95 percent percentiles from 400 saved draws per method, before numerical physical-parameter boxes. The heater-capacity infimum and supremum are open family endpoints; the sensor-capacity and coupling maxima are attained. These are not marginal intervals for an arbitrary physical parameter.", "tab:family-limits")
    correlations, rows = {}, []
    M = np.array([[-1., 0., 0.], [-1., 1., 0.], [0., 0., 1.]])
    for order in [1, 2, 12, 0]:
        model = "chain_n"+str(order) if order else "pure_delay_n0"
        source = args.results/"fits"/("joint__"+model+"_io_cold_linear_exact.json")
        inputs[str(source)] = sha(source)
        C = np.asarray(json.loads(source.read_text())["uncertainty"]["cov_log_iid_unknown_sigma"])
        for metric, covariance in [("IO", C), ("Physical", M@C@M.T)]:
            standard = np.sqrt(np.diag(covariance))
            corr = covariance/np.outer(standard, standard)
            numeric = [float(corr[0, 1]), float(corr[0, 2]), float(corr[1, 2])]
            correlations[str(order)+"_"+metric] = numeric
            rows.append([("$n="+str(order)+"$" if order else "Pure delay")+", "+metric]+[f"{v:.3f}" for v in numeric])
    write_table(args.output/"coordinate_correlations.tex", ["Model and log coordinates", r"$\rho_{12}$", r"$\rho_{13}$", r"$\rho_{23}$"], rows,
                r"Local IID correlations at the same joint cold model point. IO coordinates are $(\log K,\log\tau,\log\theta)$; physical coordinates are $(\log\Ua,\log\Cp,\log\theta)$. The physical covariance is transformed without refitting. Correlation changes reflect the chosen quantities, not extra information. One-stage entries describe the local canonical pole mode, excluding its exchanged global label.", "tab:coordinate-correlations")
    save_json(args.output/"structural_table_values.json", {"boundary_functions": values, "correlations": correlations})
    manifest = {"producer_sha256": sha(HERE/"render_structural_tables.py"), "input_sha256": inputs,
                "outputs": {name: sha(args.output/name) for name in ("family_limits.tex", "coordinate_correlations.tex", "structural_table_values.json")},
                "status": "generated_awaiting_independent_numeric_and_rendered_audit"}
    snapshot = HERE.parents[1]/"snapshot.json"
    if snapshot.exists():
        manifest["source_commit"] = json.loads(snapshot.read_text())["commit"]
        (args.output/"structural_source_snapshot.json").write_text(snapshot.read_text())
    save_json(args.output/"structural_table_manifest.json", manifest)


if __name__ == "__main__":
    main()
