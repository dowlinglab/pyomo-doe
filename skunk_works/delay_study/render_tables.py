"""Generate LaTeX tables from completed numerical phases; never refit."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from run_fits import save_json

HERE = Path(__file__).resolve().parent
ORDERS = [1, 2, 3, 4, 6, 8, 12, 0]


def key(order, coordinates="io", initialization="cold", calibration="joint"):
    family = "chain" if order else "pure_delay"
    return f"{calibration}__{family}_n{order}_{coordinates}_{initialization}_linear_exact"


def label(order):
    return "$n="+str(order)+"$" if order else "Pure delay"


def number(value, digits=3):
    return "---" if value is None or not np.isfinite(value) else f"{value:.{digits}g}"


def interval(components):
    entries = []
    for component in components:
        left = "(" if component["lower_status"] == "open_at_exploration_bound" else "["
        right = ")" if component["upper_status"] == "open_at_exploration_bound" else "]"
        entries.append(left+number(component["lower"], 4)+","+number(component["upper"], 4)+right)
    return "$"+"\\cup".join(entries)+"$"


def write_table(path, columns, header, rows, caption, reference):
    text = ["% Generated by render_tables.py; edit the producer, not this table.",
            "\\begin{table}[tbp]", "\\centering", "\\small", "\\begin{tabular}{"+columns+"}",
            "\\toprule", " & ".join(header)+r" \\", "\\midrule"]
    text.extend(" & ".join(row)+r" \\" for row in rows)
    text.extend(["\\bottomrule", "\\end{tabular}", "\\caption{"+caption+"}", "\\label{"+reference+"}", "\\end{table}", ""])
    path.write_text("\n".join(text))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, default=HERE/"results")
    parser.add_argument("--output", type=Path, default=HERE/"manuscript/tables")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    sources = {}

    def read(path):
        sources[str(path)] = hashlib.sha256(path.read_bytes()).hexdigest()
        return json.loads(path.read_text())

    def fit(order, coordinates="io", initialization="cold", calibration="joint"):
        return read(args.results/"fits"/(key(order, coordinates, initialization, calibration)+".json"))

    profile_index = read(args.results/"profile_index.json")["profiles"]
    boot_path = args.results/"bootstrap/summary.csv"
    sources[str(boot_path)] = hashlib.sha256(boot_path.read_bytes()).hexdigest()
    bootstrap = pd.read_csv(boot_path)
    ou_diagnostics = read(args.results/"ou/residual_diagnostics.json")
    parameter_rows, rmse_rows, coordinate_rows, uncertainty_rows, ou_rows = [], [], [], [], []
    for order in ORDERS:
        record = fit(order)
        p = record["fit"]["parameters"]
        parameter_rows.append([label(order), f"{p['K']:.4f}", f"{p['tau']:.3f}", f"{p['theta']:.3f}",
                               f"{.032/p['K']:.5f}", f"{.032*p['tau']/p['K']:.3f}"])
        rmses = [fit(order, calibration=calibration)["fit"]["rmse"] for calibration in ("sine", "step", "joint")]
        rmses.append(fit(order, initialization="input_equilibrated")["fit"]["rmse"])
        rmse_rows.append([label(order)]+[f"{value:.4f}" for value in rmses])
        physics = fit(order, coordinates="physics")
        F = np.asarray(record["uncertainty"]["fim_log_unit_variance"])
        M = np.array([[-1., 0., 0.], [-1., 1., 0.], [0., 0., 1.]])
        fraction = p["theta"]/(p["tau"]+p["theta"])
        N = np.array([[1., 0., 0.], [0., 1., -fraction], [0., 1., 1-fraction]])
        # Condition of J in each chosen coordinate metric, from congruent F.
        conditions = [np.sqrt(np.linalg.eigvalsh(A.T@F@A)[-1]/np.linalg.eigvalsh(A.T@F@A)[0])
                      for A in (np.eye(3), M, N)]
        difference = abs(physics["fit"]["sse"]-record["fit"]["sse"])
        mantissa, exponent = f"{difference:.1e}".split("e")
        coordinate_rows.append([label(order)]+[number(value, 4) for value in conditions]+
                               ["$"+mantissa+r"\times10^{"+str(int(exponent))+"}$"])
        if order in (1, 2, 12, 0):
            profile_name = key(order)+"__theta.json"
            profile = read(args.results/profile_index[profile_name]["path"])["profile"]
            distributions = []
            for method in ("parametric", "block60"):
                selected = bootstrap[(bootstrap.case == key(order)) & (bootstrap.method == method) &
                                     (bootstrap.coordinates == "io") & (bootstrap.parameter == "theta")]
                if len(selected) != 1 or selected.iloc[0].status != "conditional_on_model_noise_and_initialization":
                    raise RuntimeError("Bootstrap uncertainty row missing or undefined")
                row = selected.iloc[0]
                distributions.append("$["+number(row.lower, 4)+","+number(row.upper, 4)+"]$")
            ou = read(args.results/"ou"/(key(order)+".json"))
            C = ou["uncertainty"]["observed_cov_log_mean_and_length"]
            ou_sd = ou["fit"]["parameters"]["theta"]*np.sqrt(C[2][2]) if C is not None else None
            uncertainty_rows.append([label(order), interval(profile["intervals_unknown_sigma_iid"]),
                                     *distributions, number(ou_sd)])
            diagnostic = ou_diagnostics[key(order)]
            ou_rows.append([label(order), number(ou["fit"]["correlation_length_s"], 4),
                            number(ou["fit"]["sigma_stationary_ML_C"], 4),
                            number(diagnostic["sine"]["innovation_C"]["acf_lags_1_to_30"][0], 4),
                            number(diagnostic["step"]["innovation_C"]["acf_lags_1_to_30"][0], 4)])
    write_table(args.output/"joint_parameters.tex", "lrrrrr",
                ["Model", "$K$", "$\\tau$ (s)", "$\\theta$ (s)", "$\\Ua$ (W/K)", "$\\Cp$ (J/K)"],
                parameter_rows,
                "Joint cold-start estimates. Gain units are degrees Celsius per percentage-point command. Physical columns transform the IO estimates using fixed $c=0.032$ W per percentage point; they are effective-model quantities. The one-stage row uses the representative $\\tau\\geq\\theta$.",
                "tab:joint-parameters")
    write_table(args.output/"calibration_rmse.tex", "lrrrr",
                ["Model", "Sine, cold", "Step, cold", "Joint, cold", "Joint, equilibrated"], rmse_rows,
                "Calibration RMSE in degrees Celsius, excluding the initial temperature. Each entry comes from its own fitted calibration/startup combination. Equilibrated means the prescribed delay states equal the initial command, with the sensor temperature fixed by the first observation.",
                "tab:calibration-rmse")
    write_table(args.output/"coordinate_metrics.tex", "lrrrr",
                ["Model", "IO logs", "Physical logs", "Moment", "$|\\Delta S|$"],
                coordinate_rows,
                "Coordinate metrics for joint cold fits. The first three columns are sensitivity condition numbers at the same IO model point, transforming the information matrix without refitting. Moment coordinates are $(\\log K,\\log m,\\ell)$ with $m=\\tau+\\theta$ and $\\ell=\\log[\\theta/\\tau]$. The last column compares independently fitted IO and physical sums of squares, in squared degrees Celsius. Conditioning changes do not imply additional information.",
                "tab:coordinate-metrics")
    write_table(args.output/"delay_uncertainty.tex", "lcccc",
                ["Model", "IID profile set", "IID simulation", "Circular block 60", "OU local SD"],
                uncertainty_rows,
                "Joint cold delay uncertainty in seconds. Profile sets use a profiled common IID variance and retain both one-stage pole modes. Percentile intervals use 400 Gaussian simulations at fixed $\\sigma=0.25$ degrees Celsius or 400 circular residual-block refits, respectively. Bootstrap one-stage delays use the canonical pole representative. OU entries are local standard deviations with variance profiled and length included in the Hessian, not interval endpoints. These procedures make different assumptions and are not interchangeable coverage guarantees.",
                "tab:delay-uncertainty")
    write_table(args.output/"ou_diagnostics.tex", "lrrrr",
                ["Model", "Length (s)", "$\\hat\\sigma$ (${}^\\circ$C)", "ACF1, sine", "ACF1, step"], ou_rows,
                "Working OU fits to the two joint cold records. The scale is the maximum-likelihood stationary residual standard deviation. ACF1 is the centered sample lag-one correlation of filtered innovations. Strong remaining negative correlation challenges this one-component residual covariance; a high fitted likelihood does not validate it.",
                "tab:ou-diagnostics")
    save_json(args.output/"table_manifest.json", {"producer_sha256": hashlib.sha256((HERE/"render_tables.py").read_bytes()).hexdigest(),
                                                  "input_sha256": sources,
                                                  "outputs": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in args.output.glob("*.tex")},
                                                  "status": "generated_awaiting_numeric_and_rendered_audit"})


if __name__ == "__main__":
    main()
