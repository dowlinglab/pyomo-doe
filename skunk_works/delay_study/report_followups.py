"""Format and plot audited nuisance, reconstruction and prediction results.

No fitting or new uncertainty calculation occurs here. Every displayed scalar
retains its source record/field, and every table cell retains its exact format.
"""
import os
os.environ.setdefault("MPLBACKEND", "Agg")
os.environ.setdefault("MPLCONFIGDIR", "/private/tmp/tclab-matplotlib")

import argparse
import csv
import hashlib
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

import figure_style as fs
from run_fits import save_json

HERE = Path(__file__).resolve().parent
MODELS = [(1, r"$n=1$", 5, "o"), (2, r"$n=2$", 1, "s"),
          (12, r"$n=12$", 3, "^"), (0, "Pure delay", 4, "D")]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, default=HERE/"results")
    parser.add_argument("--output", type=Path, default=HERE/"manuscript/figures")
    parser.add_argument("--tables", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    args.tables.mkdir(parents=True, exist_ok=True)
    inputs, references, cells, outputs = {}, {}, {}, []
    cache = {}

    def read(path):
        path = path.resolve()
        if path not in cache:
            inputs[str(path)] = sha(path)
            cache[path] = json.loads(path.read_text())
        return cache[path]

    # Audit receipts bind the summary and all saved records, not just status.
    for phase, count in [("sensitivity", 241), ("prediction_uncertainty", 131)]:
        base = args.results/phase
        audit, manifest = read(base/"audit.json"), read(base/"manifest.json")
        if (audit["status"] != "passed" or audit["cases"] != count or manifest["failed"]
                or manifest["status"] != "complete" or len(manifest["completed"]) != count):
            raise RuntimeError("Incomplete or unaudited phase: "+phase)
        for name, digest in audit["input_sha256"].items():
            if sha(Path(name)) != digest:
                raise RuntimeError("Audited input changed: "+name)
        summary = base/"audited_summary.csv"
        if sha(summary) != audit["summary_sha256"]:
            raise RuntimeError("Audited summary changed")
        inputs[str(summary.resolve())] = sha(summary)

    def value(key, path, pointer):
        data = read(path)
        for part in pointer:
            data = data[part]
        references[key] = {"path": str(path.resolve()), "pointer": pointer, "value": data}
        return data

    def table(name, header, rows, caption, label):
        content = ["% Generated by report_followups.py; scalar sources in followup_plot_data.json.",
                   r"\begin{table}[tbp]", r"\centering\small",
                   r"\begin{tabular}{l"+"r"*(len(header)-1)+"}", r"\toprule",
                   " & ".join(header)+r" \\", r"\midrule"]
        cells[name] = []
        for title, entries in rows:
            tokens = [format(references[key]["value"], fmt) for key, fmt in entries]
            cells[name].append({"title": title, "entries": entries, "tokens": tokens})
            content.append(title+" & "+" & ".join(tokens)+r" \\")
        content += [r"\bottomrule", r"\end{tabular}", r"\caption{"+caption+"}",
                    r"\label{"+label+"}", r"\end{table}", ""]
        (args.tables/(name+".tex")).write_text("\n".join(content))

    def save(fig, name, notice):
        fs.grayscale_preview(fig, str(args.output/name))
        fs.save_fig(fig, str(args.output/name), sources=list(inputs), notes=notice)
        outputs.append(name)

    fig, axes = fs.figure(fs.MULTI_PANEL, nrows=2, sharex=True)
    modes = ["baseline", "history", "ambient_cold", "ambient_history"]
    nuisance_rows = []
    reconstruction, nuisance = {}, {}
    for order, title, color, marker in MODELS:
        model = "chain_n"+str(order) if order else "pure_delay_n0"
        stem = "joint__"+model+"_io_cold_linear_exact"
        nuisance[stem] = {"rmse": [], "theta": []}
        for mode in modes:
            path = args.results/("fits/"+stem+".json" if mode == "baseline"
                                 else "sensitivity/"+stem+"__"+mode+".json")
            for metric, pointer in [("rmse", ["fit", "rmse"] if mode == "baseline" else ["fit", "rmse_C"]),
                                    ("theta", ["fit", "parameters", "theta"] if mode == "baseline"
                                     else ["fit", "parameters_io", "theta"])]:
                key = stem+"/"+mode+"/"+metric
                nuisance[stem][metric].append(value(key, path, pointer))
        for ax, metric in zip(axes, ["rmse", "theta"]):
            ax.plot(range(4), nuisance[stem][metric], color=fs.color(color), marker=marker,
                    markersize=5, linewidth=fs.DENSE_LINEWIDTH, label=title)
        path = args.results/"sensitivity"/(stem+"__ambient_history.json")
        entries = []
        for field, pointer, fmt in [("K", ["parameters_io", "K"], ".4f"),
                                    ("theta", ["parameters_io", "theta"], ".3f"),
                                    ("ambient_sine", ["ambient_offsets_C", 0], ".3f"),
                                    ("ambient_step", ["ambient_offsets_C", 1], ".3f"),
                                    ("history_sine", ["history_fractions", 0], ".3f"),
                                    ("history_step", ["history_fractions", 1], ".3f")]:
            key = stem+"/ambient_history/"+field
            value(key, path, ["fit"]+pointer)
            entries.append((key, fmt))
        nuisance_rows.append((title, entries))
        reconstruction[stem] = {"rmse": [], "theta": []}
        entries = []
        for hold, method in [("linear", "exact"), ("left", "exact"), ("right", "exact"),
                             ("right", "backward_euler")]:
            if order == 0 and method == "backward_euler":
                continue
            case = "joint__"+model+"_io_cold_"+hold+"_"+method
            path = args.results/("fits/"+stem+".json" if hold == "linear"
                                 else "sensitivity/"+case+".json")
            baseline = hold == "linear"
            for metric, pointer in [("rmse", ["fit", "rmse"] if baseline else ["fit", "rmse"]),
                                    ("theta", ["fit", "parameters", "theta"])]:
                key = case+"/"+metric
                reconstruction[stem][metric].append(value(key, path, pointer))
                if metric == "theta":
                    entries.append((key, ".3f"))
    axes[0].set(title="(a) Calibration fit", ylabel=r"RMSE ($^\circ$C)")
    axes[1].set(title="(b) Selected delay representative", ylabel=r"$\theta$ (s)")
    axes[1].set_xticks(range(4))
    axes[1].set_xticklabels(["Cold, fixed", "History", "Ambient", "Both"])
    fig.legend(*axes[0].get_legend_handles_labels(), loc="upper center", ncol=4, bbox_to_anchor=(.5, 1.015))
    fig.tight_layout(rect=(0, 0, 1, .93), h_pad=1.5)
    save(fig, "nuisance_sensitivity", "Joint fits; independently fitted ambient offsets within +/-2 C and history fractions within [0,1]. All four selected joint ambient/history fits reach the step ambient upper bound. No measured ambient/history or physical probability is inferred. Lines join categorical assumptions.")
    table("nuisance_parameters", ["Model", r"\shortstack{$K$\\(${}^\circ$C/\%)}", r"$\theta$ (s)", r"\shortstack{$\Delta T_{a,\sin}$\\(${}^\circ$C)}", r"\shortstack{$\Delta T_{a,\rm step}$\\(${}^\circ$C)}", r"$\rho_{\sin}$", r"$\rho_{\rm step}$"], nuisance_rows,
          r"Joint fits with free ambient and history. Ambient offsets are in degrees Celsius; history fractions $\rho$ multiply the initial command. Gain units are degrees Celsius per command percentage point. Every displayed step offset reaches the imposed $+2$ degree bound. These are sensitivity fits under declared bounds, not independently measured ambient temperatures or histories.", "tab:nuisance-parameters")

    fig, axes = fs.figure(fs.MULTI_PANEL, nrows=2, sharex=True)
    for order, title, color, marker in MODELS:
        stem = "joint__"+("chain_n"+str(order) if order else "pure_delay_n0")+"_io_cold_linear_exact"
        for ax, metric in zip(axes, ["rmse", "theta"]):
            ys = reconstruction[stem][metric]
            ax.plot(range(len(ys)), ys, color=fs.color(color), marker=marker, markersize=5,
                    linewidth=fs.DENSE_LINEWIDTH, label=title)
    axes[0].set(title="(a) Fit changes with numerical assumptions", ylabel=r"RMSE ($^\circ$C)")
    axes[1].set(title="(b) Delay changes at similar fit error", ylabel=r"$\theta$ (s)")
    axes[1].set_xticks(range(4))
    axes[1].set_xticklabels(["Linear\nexact", "Left\nexact", "Right\nexact", "Right\nEuler"])
    fig.legend(*axes[0].get_legend_handles_labels(), loc="upper center", ncol=4, bbox_to_anchor=(.5, 1.015))
    fig.tight_layout(rect=(0, 0, 1, .93), h_pad=1.5)
    save(fig, "reconstruction_sensitivity", "Joint cold refits at recorded observation times. Exact denotes exact LTI propagation for the stated command hold; Euler denotes backward Euler with right-end commands. Pure-delay Euler is not defined or plotted. No confidence interval is implied by categorical connections.")

    path = args.results/"prediction_uncertainty/audited_summary.csv"
    with path.open() as handle:
        prediction_rows = list(csv.DictReader(handle))
    validation_name = sorted(read(args.results/"manifest.json")["validation_files"])[0]
    methods = [("local", "iid_unknown_quotient_dof", "IID fitted"),
               ("local", "hac60_quotient_dof", "HAC60"),
               ("ou", "ou_observed_noise_profiled", "OU fitted"),
               ("bootstrap", "bootstrap_block60", "Block60")]
    fig, axes = fs.figure(fs.MULTI_PANEL, nrows=2, sharex=True)
    prediction_table = []
    for order, title, color, marker in MODELS:
        stem = "joint__"+("chain_n"+str(order) if order else "pure_delay_n0")+"_io_cold_linear_exact"
        widths = [[], []]
        for phase, method, method_title in methods:
            key_case = phase+"__"+stem+("__block60" if phase == "bootstrap" else "")
            for i, experiment in enumerate(["sine", validation_name]):
                matches = [(j, row) for j, row in enumerate(prediction_rows)
                           if row["case"] == key_case and row["method"] == method and row["experiment"] == experiment]
                if len(matches) != 1:
                    raise RuntimeError("Prediction summary selection is not unique")
                j, row = matches[0]
                key = key_case+"/"+method+"/"+experiment
                width = float(row["mean_band_median_width_C"])
                references[key] = {"path": str(path.resolve()), "csv_row": j,
                                   "column": "mean_band_median_width_C", "value": width}
                widths[i].append(width)
                if phase in ("local", "ou") and method != "hac60_quotient_dof":
                    ckey = key+"/containment"
                    references[ckey] = {"path": str(path.resolve()), "csv_row": j,
                                       "column": "observed_fraction_inside_prediction_band_defined_points",
                                       "value": float(row["observed_fraction_inside_prediction_band_defined_points"])}
            if phase in ("local", "ou") and method != "hac60_quotient_dof":
                a = key_case+"/"+method+"/sine"
                b = key_case+"/"+method+"/"+validation_name
                prediction_table.append((title+", "+method_title, [(a, ".3f"), (b, ".3f"), (b+"/containment", ".3f")]))
        for ax, ys in zip(axes, widths):
            ax.plot(range(4), ys, color=fs.color(color), marker=marker, markersize=5,
                    linewidth=fs.DENSE_LINEWIDTH, label=title)
    axes[0].set(title="(a) Calibration sine record", ylabel=r"Median width ($^\circ$C)")
    axes[1].set(title="(b) Held-out record V01", ylabel=r"Median width ($^\circ$C)")
    axes[1].set_xticks(range(4))
    axes[1].set_xticklabels([row[2] for row in methods])
    fig.legend(*axes[0].get_legend_handles_labels(), loc="upper center", ncol=4, bbox_to_anchor=(.5, 1.015))
    fig.tight_layout(rect=(0, 0, 1, .93), h_pad=1.5)
    save(fig, "prediction_mean_widths", "Median pointwise nominal 95% thermal-mean band widths, excluding conditioned first samples. Working local IID, HAC60, fitted OU observed Hessian and block60 percentile methods have different assumptions. V01 is the first sorted validation file, selected by the existing file-code map, without refitting. No unconditional coverage claim.")
    table("prediction_widths", ["Model, method", r"\shortstack{Sine width\\(${}^\circ$C)}", r"\shortstack{V01 width\\(${}^\circ$C)}", "V01 obs. fraction"], prediction_table,
          r"Median pointwise mean-band widths and descriptive V01 containment by nominal observation-prediction bands. The last column uses observation bands with an added fitted IID or OU marginal future-error variance; it is not containment by the narrower mean bands. V01 is defined in Table~\ref{tab:validation-files}. These fractions on one observed record are not repeated-experiment coverage estimates. HAC and block-residual methods supply no future-error law here and therefore no observation-band containment.", "tab:prediction-widths")
    data_path = args.output/"followup_plot_data.json"
    save_json(data_path, {"references": references, "table_cells": cells,
                          "nuisance": nuisance, "reconstruction": reconstruction,
                          "validation_file": validation_name})
    manifest = {"input_sha256": inputs, "data_sha256": sha(data_path), "figures": outputs,
                "table_sha256": {name+".tex": sha(args.tables/(name+".tex")) for name in cells},
                "producer_sha256": sha(Path(__file__)), "style_sha256": sha(HERE/"figure_style.py"),
                "status": "generated_awaiting_numeric_and_visual_review"}
    snapshot = HERE.parents[1]/"snapshot.json"
    if snapshot.exists():
        manifest["source_commit"] = json.loads(snapshot.read_text())["commit"]
        (args.output/"followup_source_snapshot.json").write_text(snapshot.read_text())
    save_json(args.output/"followup_figure_manifest.json", manifest)


if __name__ == "__main__":
    main()
