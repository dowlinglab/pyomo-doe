"""Generate the teaching summary from verified saved numbers."""

import hashlib
import json
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    comparison = json.loads((HERE / "results/saved_comparison.json").read_text())
    audit = json.loads((HERE / "results/audit.json").read_text())
    assert audit["status"] == "passed"
    assert max(r["FIM_relative_error"] for r in audit["evaluations"]) < 3.3e-7
    assert max(r["local_sd_max_relative_error"] for r in audit["evaluations"]) < 2.6e-5
    assert max(comparison["independently_fitted_joint_n1_vs_original_max_prediction_difference_C"].values()) < 1.5e-7
    coverage_path = HERE.parent / "results/coverage_summary/coverage_summary.csv"
    with coverage_path.open() as source:
        coverage = list(csv.DictReader(source))
    for order, method, count in [(1, "iid_estimated_sigma", 66), (2, "iid_estimated_sigma", 56),
                                 (1, "hac60", 235), (2, "hac60", 249)]:
        matches = [r for r in coverage if r["case"] == f"joint__chain_n{order}_io_cold_linear_exact"
                   and r["parameter"] == "theta" and r["coordinates"] == "io"
                   and r["true_noise"] == "ou60" and r["method"] == method]
        assert len(matches) == 1 and int(matches[0]["covered"]) == count and int(matches[0]["defined"]) == 300
    rows = ["| Model | Joint calibration RMSE (C) | Pooled held-out RMSE (C) |",
            "|---|---:|---:|"]
    for row in comparison["calibration_and_validation"]:
        if row["calibration"] == "joint":
            name = "Original four-parameter" if row["model"] == "original" else f"n={row['model']}"
            rows.append(f"| {name} | {row['calibration_rmse_C']:.4f} | {row['pooled_validation_rmse_C']:.4f} |")
    uncertainty = ["| Model | Independent residual resampling, delay interval (s) | 60-sample blocks (s) | Width multiplier |",
                   "|---|---:|---:|---:|"]
    for row in comparison["delay_intervals"]:
        a, b = row["block1"], row["block60"]
        uncertainty.append(f"| n={row['order']} | [{a['lower_s']:.2f}, {a['upper_s']:.2f}] | [{b['lower_s']:.2f}, {b['upper_s']:.2f}] | {row['block60_to_block1_width_ratio']:.2f} |")
    designs = ["| Model | Working error law | Constant-input delay SD (s) | Selected-input delay SD (s) | D-information multiplier |",
               "|---|---|---:|---:|---:|"]
    for name in ["n1_iid", "n2_iid", "n1_ou60", "n2_ou60"]:
        d = json.loads((HERE / "results" / (name + ".json")).read_text())
        law = "IID" if not d["working_correlation_length_s"] else "Known OU, 60 s"
        designs.append(f"| n={d['order']} | {law} | {d['baseline']['local_parameter_sd'][2]:.3f} | {d['selected']['local_parameter_sd'][2]:.3f} | {d['D_efficiency_gain']:.2f} |")
    text = """# Reduced TC-Lab models for teaching

Generated by `render_notes.py` from the saved comparisons and audited Pyomo.DoE
demonstration. This supplement leaves the overnight manuscript and its release
artifacts unchanged. Scientific interpretation is agent-authored and awaits review.

Use n=1 for the core exercise. It retains two dynamic states but estimates three
transfer parameters, K, tau and theta. Add n=2 as an extension on delay shape,
model choice and numerical discretization; it has three dynamic states and still
three unknown parameters. The available fits do not justify higher orders as a
requirement for the introductory exercise.

The original four physical parameters describe only three independent transfer
coefficients under the studied single-output model and initial conditions.
The n=1 model represents that same response. The independently optimized joint
fits differ in predicted temperature by less than 1.5e-7 C on both calibration
and validation records. Reduction removes an unidentifiable direction without
improving these predictions.

""" + "\n".join(rows) + """

These are cold-start fits; initialization can reverse the order ranking. The
n=2 joint fit has about 12.5% higher calibration RMSE and 0.06% higher held-out
RMSE. Its step-only calibration improves from 0.1573 to 0.1529 C, about 2.8%.
Most held-out error is associated algebraically with record-specific mean errors;
the data do not establish their cause. More delay stages do not resolve that issue.

The n=1 pole labels can also be exchanged globally. A convention such as tau >=
theta selects a representative, without proving which lag is a physical transport
delay. A full-rank local FIM does not detect this second global mode. The n=2
model distinguishes its repeated delay pole from a distinct thermal pole;
coincident poles remain nonregular.

## Residual dependence

The following nominal 95% percentile intervals use 400 refits per method with
the same centered empirical residuals. The comparison changes block length,
without changing the marginal residual pool. One-stage values use the canonical
short-delay pole representative; the swapped mode remains possible.

""" + "\n".join(uncertainty) + """

Sixty samples are roughly one minute in these records. The widening shows
sensitivity to retained dependence, without establishing that this block length
delivers correct coverage. Independent Gaussian simulation at sigma=0.25 C gives
still narrower intervals, but also changes the error scale and should be kept
separate from this comparison.

In the controlled synthetic OU60 experiment, nominal 95% IID fitted-variance
delay intervals covered 66/300 cases for n=1 and 56/300 for n=2. HAC60 increased
these to 235/300 and 249/300. The thermal mean was correct by construction.
Thus covariance assumptions alone can cause severe undercoverage. The real-data
one-component OU fits still have innovation lag-one correlations near -0.5;
neither OU fitting nor block resampling establishes an adequate discrepancy model.

## Pyomo.DoE demonstration

`pyomo_doe_reduced.py` implements a Parmest Experiment subclass with three unknown
parameters and the four suffixes required by Pyomo.DoE. Both n=1 and n=2 produce
full-rank 3-by-3 local information matrices. Relative-parameter scaling makes
the objective concern log K, log tau and log theta. The original four-parameter
single-output model has rank three, so its true four-dimensional determinant is
zero; finite-difference roundoff cannot supply the missing information.

The hypothetical experiment lasts 900 s, observes temperature every 10 s, and
uses seven affine command knots 150 s apart. Commands lie between 0 and 100%,
integrated command is at most 45000 percent-seconds, and adjacent knots differ
by at most 60 percentage points. Nominal collocation temperatures have an upper
limit of 84.99 C with ambient fixed at 22.2 C. Each design uses two starting
waveforms, no prior FIM, and nominal parameters from the saved joint cold fit.

""" + "\n".join(designs) + """

Each row is optimized for its own error assumption and compared with a constant
50% command under that same assumption. The D-information multiplier is
(det(F_selected)/det(F_constant))^(1/3). It describes local information, rather
than measured improvement in prediction accuracy. The SDs are conditional local
Fisher-information calculations at hypothetical sigma=0.25 C; they are not the
real-data bootstrap intervals above.

Pyomo.DoE's measurement_error suffix takes standard deviations and its built-in
weighting assumes independent errors. The OU cases use transformed mean outputs:
the first observation is unchanged and later values use the stationary OU
innovation transform. This corresponds to J.T @ inverse(Sigma) @ J for a known
correlation length and scale. It does not estimate covariance parameters or
establish that OU errors describe the TC-Lab residuals.

The separate `audit_demo.py` checks all 16 baseline/start/refined information
matrices and local SDs against complex-step sensitivities from the overnight
simulator with explicit full covariance inversion. The largest relative FIM
error is below 3.3e-7 and the largest relative SD error below 2.6e-5. All four
selected nominal trajectories remain below 85 C on an independent 0.25-s grid.
The dense audit covers only the proposed 900-s window and these fitted points;
it is not a hardware or continuous-time safety certificate.

Three-point Radau collocation uses 90 finite elements for n=1 and 180 for n=2;
the saved selected designs were also evaluated with twice those counts. The n=2
coarse grid failed the 0.001 C mean check and was refined. An unnecessary lower
bound on the collocation temperature polynomial also caused a false infeasibility
near startup; its removal preserves the upper temperature limit. These trials
and the sensitivity-evaluation correction are retained in `trial_failures.json`.
All accepted evaluations keep the original 0.001 C mean tolerance.

## Reproduction

Use the existing pyomo-doe-maint environment for `pyomo_doe_reduced.py`, with
BLAS/OpenMP threads set to one. Run `--order 1 --nfe 90` or `--order 2 --nfe 180`,
add `--length 60` for the fixed OU comparator, and use `--optimize --output PATH`.
The original study interpreter runs `compare_saved_results.py` and `audit_demo.py`;
either environment can run `render_notes.py`. Source and input hashes are retained
in the result JSON and audit. The Pyomo version used here is 6.10.0.

The four designs and their verification results are saved under `results/`.

Pyomo's [official quick-start guide](https://pyomo.readthedocs.io/en/stable/explanation/analysis/doe/guide.html)
describes the Experiment interface and independent-error assumption.
"""
    (HERE / "README.md").write_text(text)
    inputs = {str(p.relative_to(HERE)): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in sorted(HERE.rglob("*")) if p.is_file()
              and p.suffix in {".py", ".json", ".md"}
              and p.name != "manifest.json" and "__pycache__" not in p.parts}
    (HERE / "manifest.json").write_text(json.dumps({"status": "completed_and_audited",
        "files_sha256": inputs, "coverage_source_sha256": hashlib.sha256(coverage_path.read_bytes()).hexdigest(),
        "editorial_review": "Agent pass against no-ai-slop principles/eval: direct claims, numerical scope and uncertainty retained, no inflated importance or formulaic contrasts. Human scientific review pending.",
        "scope": "Separate teaching follow-up; the overnight release remains frozen."}, indent=2) + "\n")


if __name__ == "__main__":
    main()
