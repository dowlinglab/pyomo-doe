"""Format the teaching appendix tables from saved, audited results."""

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLES = HERE.parent / "manuscript" / "tables"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def table(name, caption, columns, header, rows, label):
    text = ["% Generated by teaching_followup/render_report_tables.py",
            r"\begin{table}[htbp]", r"\centering", r"\small",
            "\\caption{" + caption + "}", "\\label{" + label + "}",
            "\\begin{tabular}{" + columns + "}", r"\toprule",
            header + r" \\", r"\midrule"]
    text.extend(" & ".join(row) + r" \\" for row in rows)
    text.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    path = TABLES / (name + ".tex")
    path.write_text("\n".join(text))
    return path


def main():
    inputs = [HERE / "results/saved_comparison.json", HERE / "results/audit.json",
              HERE / "figures/plot_receipt.json"]
    saved = json.loads(inputs[0].read_text())
    audit = json.loads(inputs[1].read_text())
    assert audit["status"] == "passed"
    plot = json.loads(inputs[2].read_text())
    sources = {}
    for order in [1, 2]:
        for noise in ["iid", "ou60"]:
            path = HERE / "results" / f"n{order}_{noise}.json"
            inputs.append(path)
            sources[f"n{order}_{noise}"] = json.loads(path.read_text())
            assert plot["source_sha256"][str(path.relative_to(HERE))] == sha(path)
    outputs = []
    names = {"original": "Original four-parameter", "1": "$n=1$", "2": "$n=2$"}
    rows = [[names[r["model"]], f'{r["calibration_rmse_C"]:.4f}',
             f'{r["pooled_validation_rmse_C"]:.4f}']
            for r in saved["calibration_and_validation"] if r["calibration"] == "joint"]
    outputs.append(table("teaching_prediction", "Cold-start joint fits and pooled held-out prediction error. RMSE is in degrees Celsius.",
                         "lrr", "Model & Calibration RMSE & Held-out RMSE", rows, "tab:teaching-prediction"))
    rows = []
    for r in saved["delay_intervals"]:
        bounds = [f'[{r[k]["lower_s"]:.2f}, {r[k]["upper_s"]:.2f}]' for k in ["block1", "block60"]]
        rows.append([f'$n={r["order"]}$', *bounds, f'{r["block60_to_block1_width_ratio"]:.2f}'])
    outputs.append(table("teaching_blocks", "Delay percentile intervals (s) from the same centered residual pool; 400 refits per method. Width ratio compares 60-sample blocks with independent resampling.",
                         "lrrr", "Model & Independent & 60-sample blocks & Width ratio", rows, "tab:teaching-blocks"))
    rows = []
    for name in ["n1_iid", "n2_iid", "n1_ou60", "n2_ou60"]:
        r = sources[name]
        rows.append([f'$n={r["order"]}$', "IID" if name.endswith("iid") else "Known OU60",
                     f'{r["baseline"]["local_parameter_sd"][2]:.3f}',
                     f'{r["selected"]["local_parameter_sd"][2]:.3f}', f'{r["D_efficiency_gain"]:.2f}'])
    outputs.append(table("teaching_doe", "Conditional local delay standard deviations (s) and D-information multipliers for the selected and constant-input designs. Each row uses its own working covariance and a hypothetical marginal error SD of $0.25\\,{}^\\circ\\mathrm C$.",
                         "llrrr", "Model & Error law & Constant SD & Selected SD & D multiplier", rows, "tab:teaching-doe"))
    keys = ["n1_iid", "n1_ou60", "n2_iid", "n2_ou60"]
    rows = []
    for i, t in enumerate(sources[keys[0]]["command_knots_s"]):
        rows.append([f"{t / 60:.1f}", *[f'{sources[k]["selected"]["controls"][i]:.2f}' for k in keys]])
    outputs.append(table("teaching_commands", "Selected heater command knots (percent), rounded to two decimals. Commands interpolate linearly; exact values are saved in the command CSV.",
                         "rrrrr", "Time (min) & $n=1$ IID & $n=1$ OU60 & $n=2$ IID & $n=2$ OU60", rows, "tab:teaching-commands"))
    receipt = {"status": "rendered_from_saved_audited_results", "producer_sha256": sha(Path(__file__)),
               "inputs_sha256": {str(p.relative_to(HERE)): sha(p) for p in inputs},
               "tables_sha256": {p.name: sha(p) for p in outputs},
               "scope": "Formatting and source bindings only; numerical validity belongs to the separate saved audits."}
    (HERE / "report_tables_receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({"tables": len(outputs), "input_files": len(inputs)}))


if __name__ == "__main__":
    main()
